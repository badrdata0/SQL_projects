-- 1. Create the database
USE master;                                        -- switch to master
GO
-- Create the database only if it does not exist yet (safe to re-run)
IF DB_ID('customer_behavior') IS NULL CREATE DATABASE customer_behavior;
GO
USE customer_behavior;                             -- switch to the project database
GO

-- Check that the database exists: customer_behavior must appear in the list
SELECT name FROM sys.databases;
GO

-- 2. Load the data
-- The "customer" table is loaded from Python (Customer_Shopping_Behavior_Analysis.ipynb)
SELECT TOP 20 * FROM customer;                     -- check that the data is loaded
GO

-- Q1. Total revenue generated by male vs. female customers
SELECT gender,                                        -- customer gender
       SUM(purchase_amount) AS revenue                -- total revenue per gender
FROM customer
GROUP BY gender;                                      -- one row per gender
GO

-- Q2. Customers who used a discount but still spent more than the average purchase amount
SELECT customer_id,                                   -- customer identifier
       purchase_amount                                -- amount spent
FROM customer
WHERE discount_applied = 'Yes'                        -- only discounted purchases
  AND purchase_amount >= (SELECT AVG(CAST(purchase_amount AS DECIMAL(10,2))) FROM customer);   -- above overall average
GO

-- Q3. Top 5 products with the highest average review rating
SELECT TOP 5 item_purchased,                          -- product name
       ROUND(AVG(CAST(review_rating AS DECIMAL(10,2))), 2) AS avg_product_rating   -- average rating, 2 decimals
FROM customer
GROUP BY item_purchased                               -- one row per product
ORDER BY avg_product_rating DESC;                     -- best rated first
GO

-- Q4. Average purchase amount: Standard vs. Express shipping
SELECT shipping_type,                                 -- shipping method
       ROUND(AVG(CAST(purchase_amount AS DECIMAL(10,2))), 2) AS avg_purchase_amount   -- average spend
FROM customer
WHERE shipping_type IN ('Standard', 'Express')        -- only these two methods
GROUP BY shipping_type;
GO

-- Q5. Do subscribed customers spend more? Average spend and total revenue by subscription status
SELECT subscription_status,                           -- Yes / No
       COUNT(customer_id) AS total_customers,         -- number of customers
       ROUND(AVG(CAST(purchase_amount AS DECIMAL(10,2))), 2) AS avg_spend,   -- average spend
       SUM(purchase_amount) AS total_revenue          -- total revenue
FROM customer
GROUP BY subscription_status
ORDER BY total_revenue, avg_spend DESC;               -- sort by revenue, then average spend
GO

-- Q6. Top 5 products with the highest percentage of discounted purchases
SELECT TOP 5 item_purchased,                          -- product name
       ROUND(100.0 * SUM(CASE WHEN discount_applied = 'Yes' THEN 1 ELSE 0 END) / COUNT(*), 2) AS discount_rate   -- % of sales with discount
FROM customer
GROUP BY item_purchased
ORDER BY discount_rate DESC;                          -- highest discount reliance first
GO

-- Q7. Segment customers into New, Returning and Loyal based on previous purchases
WITH customer_type AS (                               -- temporary result (CTE)
    SELECT customer_id,
           previous_purchases,
           CASE
               WHEN previous_purchases = 1 THEN 'New'                    -- first purchase
               WHEN previous_purchases BETWEEN 2 AND 10 THEN 'Returning' -- 2 to 10 purchases
               ELSE 'Loyal'                                              -- more than 10 purchases
           END AS customer_segment
    FROM customer
)
SELECT customer_segment,                              -- segment name
       COUNT(*) AS number_of_customers                -- customers per segment
FROM customer_type
GROUP BY customer_segment;
GO

-- Q8. Top 3 most purchased products within each category
WITH item_counts AS (                                 -- orders per product and category
    SELECT category,
           item_purchased,
           COUNT(customer_id) AS total_orders,        -- number of orders
           ROW_NUMBER() OVER (PARTITION BY category ORDER BY COUNT(customer_id) DESC) AS item_rank   -- rank inside each category
    FROM customer
    GROUP BY category, item_purchased
)
SELECT item_rank, category, item_purchased, total_orders
FROM item_counts
WHERE item_rank <= 3;                                 -- keep top 3 per category
GO

-- Q9. Are repeat buyers (more than 5 previous purchases) also likely to subscribe?
SELECT subscription_status,                           -- Yes / No
       COUNT(customer_id) AS repeat_buyers            -- number of repeat buyers
FROM customer
WHERE previous_purchases > 5                          -- repeat buyers only
GROUP BY subscription_status;
GO

-- Q10. Revenue contribution of each age group
SELECT age_group,                                     -- age segment
       SUM(purchase_amount) AS total_revenue          -- total revenue per age group
FROM customer
GROUP BY age_group
ORDER BY total_revenue DESC;                          -- highest revenue first
GO

